// Builds the single-file fact collector that ships inside the skill: `npm run bundle`.
// The MCP server is left out, so the bundle has no dependencies beyond Node itself.
import { join } from "node:path";
import { build } from "esbuild";
import { VERSION } from "../src/version.ts";

const root = join(import.meta.dirname, "..");
const outfile = join(root, "skills", "before-you-pr", "scripts", "before-you-pr.mjs");

await build({
  entryPoints: [join(root, "src", "cli.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "none",
  banner: { js: `// before-you-pr ${VERSION}: generated by \`npm run bundle\` from src/. Do not edit.` },
  plugins: [
    {
      name: "leave-out-mcp",
      setup(b) {
        b.onResolve({ filter: /\/mcp\.ts$/ }, (args) => ({ path: args.path, external: true }));
      },
    },
  ],
});
console.log(`wrote ${outfile}`);
